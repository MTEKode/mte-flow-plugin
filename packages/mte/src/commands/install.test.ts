import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { after, before, describe, it } from 'node:test'
import { expect } from '../test-support/expect.ts'

const CLI = new URL('../cli.ts', import.meta.url).pathname
const ASSETS = new URL('../../assets/', import.meta.url).pathname
let root: string

before(() => {
  root = mkdtempSync(join(tmpdir(), 'mte-install-'))
})
after(() => rmSync(root, { recursive: true, force: true }))

const asset = (file: string): string => readFileSync(join(ASSETS, 'skill', file), 'utf8')

function workspace(name: string): string {
  const ws = join(root, name)
  mkdirSync(ws, { recursive: true })
  return ws
}

function install(ws: string) {
  return spawnSync(process.execPath, [CLI, 'install', '--workspace', ws], { cwd: root, encoding: 'utf8' })
}

const readJson = (path: string): Record<string, any> => JSON.parse(readFileSync(path, 'utf8'))
const expectedEntry = { command: process.execPath, args: [realpathSync(CLI), 'memory'] }

describe('mte install .mcp.json', () => {
  it('writes a runnable node+entry memory server, idempotently, preserving unrelated keys', () => {
    const ws = workspace('mcp')
    writeFileSync(join(ws, '.mcp.json'), JSON.stringify({ mcpServers: { other: { command: 'x' } } }))
    expect(install(ws).status).toBe(0)
    const doc = readJson(join(ws, '.mcp.json'))
    expect(Object.keys(doc.mcpServers).sort()).toEqual(['mte-memory', 'other'])
    expect(doc.mcpServers.other).toEqual({ command: 'x' })
    expect(doc.mcpServers['mte-memory']).toEqual(expectedEntry)

    const path = join(ws, '.mcp.json')
    const beforeText = readFileSync(path, 'utf8')
    const beforeMtime = statSync(path).mtimeMs
    expect(install(ws).status).toBe(0)
    expect(readFileSync(path, 'utf8')).toBe(beforeText)
    expect(statSync(path).mtimeMs).toBe(beforeMtime)
  })

  it('replaces the retired { command: "mte", args: [...role] } entry', () => {
    const ws = workspace('mcp-legacy')
    writeFileSync(
      join(ws, '.mcp.json'),
      JSON.stringify({ mcpServers: { 'mte-memory': { command: 'mte', args: ['memory', '--role', 'orchestrator'] } } })
    )
    expect(install(ws).status).toBe(0)
    expect(readJson(join(ws, '.mcp.json')).mcpServers['mte-memory']).toEqual(expectedEntry)
  })

  it('aborts on invalid JSON without writing it', () => {
    const ws = workspace('mcp-bad-json')
    const path = join(ws, '.mcp.json')
    writeFileSync(path, '{oops')
    const res = install(ws)
    expect(res.status).toBe(1)
    expect(readFileSync(path, 'utf8')).toBe('{oops')
  })
})

describe('mte install .agents cleanup', () => {
  it('removes stale generated mte-flow and legacy mte copies; never writes .agents', () => {
    const ws = workspace('agents')
    mkdirSync(join(ws, '.agents/skills/mte-flow'), { recursive: true })
    writeFileSync(join(ws, '.agents/skills/mte-flow/SKILL.md'), asset('SKILL.md'))
    writeFileSync(join(ws, '.agents/skills/mte-flow/playbook.md'), 'stale 0.3-era playbook with opencode text')
    mkdirSync(join(ws, '.agents/skills/mte'), { recursive: true })
    writeFileSync(join(ws, '.agents/skills/mte/SKILL.md'), '<!-- generated by mte install; do not edit -->\nlegacy skill')
    writeFileSync(join(ws, '.agents/skills/mte/playbook.md'), 'legacy playbook')
    mkdirSync(join(ws, '.agents/skills/other'), { recursive: true })
    writeFileSync(join(ws, '.agents/skills/other/SKILL.md'), 'unrelated skill')

    expect(install(ws).status).toBe(0)
    expect(existsSync(join(ws, '.agents/skills/mte-flow'))).toBe(false)
    expect(existsSync(join(ws, '.agents/skills/mte'))).toBe(false)
    expect(readdirSync(join(ws, '.agents/skills'))).toEqual(['other'])
    // Install writes the Claude copy only.
    expect(readFileSync(join(ws, '.claude/skills/mte-flow/SKILL.md'), 'utf8')).toBe(asset('SKILL.md'))
  })

  it('leaves a foreign .agents skill untouched', () => {
    const ws = workspace('agents-foreign')
    mkdirSync(join(ws, '.agents/skills/mte-flow'), { recursive: true })
    writeFileSync(join(ws, '.agents/skills/mte-flow/SKILL.md'), '---\nname: mte-flow\n---\nhand-written\n')
    writeFileSync(join(ws, '.agents/skills/mte-flow/playbook.md'), 'hand-written playbook')
    expect(install(ws).status).toBe(0)
    expect(readFileSync(join(ws, '.agents/skills/mte-flow/SKILL.md'), 'utf8')).toContain('hand-written')
    expect(readFileSync(join(ws, '.agents/skills/mte-flow/playbook.md'), 'utf8')).toBe('hand-written playbook')
  })

  it('a fresh workspace gains no .agents directory', () => {
    const ws = workspace('agents-clean')
    expect(install(ws).status).toBe(0)
    expect(existsSync(join(ws, '.agents'))).toBe(false)
  })
})

describe('playbook asset', () => {
  it('has no orchestration link and no retired question-queue mentions', () => {
    const text = asset('playbook.md')
    expect(text).not.toContain('orchestration link')
    for (const retired of ['ask_orq', 'answer_orq', 'get_pending_questions']) {
      expect(text).not.toContain(retired)
    }
  })

  it('documents independent explorers (no mesh) and the worker_done task/dispatch ids', () => {
    const text = asset('playbook.md')
    expect(text).not.toContain('orchestration send --to dispatch:')
    expect(text).toContain('sin conexión entre ellos')
    expect(text).toContain('record_qa')
    expect(text).toContain('orca orchestration ask')
    expect(text).toMatch(/worker_done[^\n]*--task-id/)
    expect(text).toMatch(/worker_done[^\n]*--dispatch-id/)
  })
})
